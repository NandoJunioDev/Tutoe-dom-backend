CREATE Table endereco(
id  bigint generated by default as identity
 PRIMARY KEY,

 rua SMALLINT NOT NULL,
 gondola SMALLINT not null ,
 andar SMALLINT  NOT NULL,
 lado SMALLINT  NOT NULL CHECK(lado in (1,2)),
 posicao SMALLINT  NOT NULL,

 setor_id   BIGINT NOT  NULL  REFERENCES setor(id),


UNIQUE (setor_id, rua, gondola, andar, lado, posicao)

);