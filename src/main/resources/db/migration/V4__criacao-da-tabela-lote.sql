CREATE TABLE lote(

 id  bigint generated by default as identity
 PRIMARY KEY,

    produto_id BIGINT not NULL REFERENCES produtos(id),
    endereco_id BIGINT not NULL REFERENCES endereco(id),

    codigo_lote  VARCHAR (30) NOT NULL,
    quantidade INTEGER NOT NULL  check(quantidade>=0),

    data_entrada DATE NOT NULL,

    data_validade DATE,

    enviado_para_promocao_em TIMESTAMP, 

    UNIQUE (produto_id, codigo_lote)

);
CREATE INDEX idx_lote_data_validade ON lote (data_validade);